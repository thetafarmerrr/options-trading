def main():
    dry = "--dry-run" in sys.argv
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
        fieldnames = list(rows[0].keys())

    tgt = [r for r in rows if r.get("date") == BATCH]
    assert len(tgt) == 10, f"批次 {BATCH} 应有 10 行，实际 {len(tgt)}"
    assert set(REASON) == {r["variety"] for r in tgt}, "品种集合不一致"
    for r in tgt:
        assert not r["actual_reason_coach"], f"{r['variety']}: actual_reason_coach 已有值，拒绝覆盖"
        assert not r["user_reason"] or True
    for v, t in REASON.items():
        assert "〔源" in t, f"{v}: 缺来源标注（违 9/28 先搜后写）"
        assert "⚠️" in t, f"{v}: 缺反方/未兑现项"

    print(f"批次 {BATCH} → compare 2026/10/12：待写 actual_reason_coach {len(tgt)} 行")
    for r in tgt:
        v = r["variety"]
        d, dd = ACTUAL[v]
        print(f"  {v:<4} 实际 {dd:+6.2f}pp → {d:<5} · coach 事前 {r['coach_pred']:<5}"
              f" · user 事前 {r['user_pred']:<5} · reason {len(REASON[v])} 字")

    if dry:
        print("\n--dry-run：未落盘。")
        return

    b = open(CSV_PATH, "rb").read()
    n_before = (b.count(b"\n"), b.count(b"\r\n"))
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = f"/tmp/iv_direction_pred.csv.{stamp}.bak"
    shutil.copy2(CSV_PATH, bak)

    for r in tgt:
        r["actual_reason_coach"] = REASON[r["variety"]]

    tmp = CSV_PATH + ".tmp"
    with open(tmp, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    os.replace(tmp, CSV_PATH)

    # ── 回执（只打印行数/CRLF/断言，**不回显正文**）────────────
    b2 = open(CSV_PATH, "rb").read()
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows2 = list(csv.DictReader(f))
    tgt2 = [r for r in rows2 if r.get("date") == BATCH]
    assert len(rows2) == len(rows), "行数变了，拒绝"
    assert all(r["actual_reason_coach"] for r in tgt2), "有行未写"
    assert all(not r["actual_reason"] for r in tgt2), "用户列被污染"
    assert all(r["actual"] == "" for r in tgt2), "机械列被污染（应归第 ② 步）"
    print(f"\n回执：总行数 {len(rows2)}（未变）· 本批 {len(tgt2)} · 列数 {len(rows2[0])}")
    print(f"      actual_reason_coach 已写 {sum(1 for r in tgt2 if r['actual_reason_coach'])}/10"
          f" · user_reason 仍空 {sum(1 for r in tgt2 if not r['user_reason'])}/10"
          f" · actual 仍空 {sum(1 for r in tgt2 if not r['actual'])}/10")
    print(f"      LF {n_before[0]} → {b2.count(b'\n')} · CRLF {n_before[1]} → {b2.count(b'\r\n')}（须为 0）")
    print(f"      备份 {bak}")
    print(f"\n▶ 第 ① 步完成。现在等她口述 `actual_reason`（第 ② 步）。")


if __name__ == "__main__":
    main()

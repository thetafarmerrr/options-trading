    before = json.loads(json.dumps(d["events"], ensure_ascii=False))
    old_map = {e["品种码"]: e for e in before}
    assert set(old_map) == set(NEW), f"品种集不匹配：{set(old_map) ^ set(NEW)}"
    assert len(d["events"]) == 10

    # ── 改动只允许落在 催化 / 卖方预警 / 概率 三个字段 ──
    ALLOWED = {"催化", "卖方预警", "概率"}
    churn = []
    for e in d["events"]:
        v = e["品种码"]
        for k, val in NEW[v].items():
            assert k in ALLOWED, f"{v} 试图改非白名单字段 {k}"
            if e[k] != val:
                churn.append((v, k))
            e[k] = val

    d["scan_date"] = UPD
    d["valid_from"] = UPD
    d["valid_until"] = UNTIL   # 覆盖 10/19 批 10/26 · 10/21 批 10/28 · 10/22 批 10/29

    print(f"品种 {len(d['events'])} 条 · 快照 {d['scan_date']} · 有效 {d['valid_from']} → {d['valid_until']}")
    print(f"字段改动 {len(churn)} 处（白名单: {sorted(ALLOWED)}）")
    for v, k in churn:
        if k == "概率":
            print(f"  ⚠️ {v} 概率：{old_map[v][k]} → {NEW[v][k]}")
    print("⚠️ 本快照生成于窗口开启前 → 窗内已实现事实 = 0 条；主体为〔前窗·10/19–10/26〕状态基线。")

    if dry:
        print("\n--dry-run：未落盘。")
        return

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = f"/tmp/weekly_event_scan.json.{stamp}.bak"
    shutil.copy2(PATH, bak)
    tmp = PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")
    os.replace(tmp, PATH)

    # ── 打印回核（9/16 立规）──
    with open(PATH, encoding="utf-8") as f:
        back = json.load(f)
    bmap = {e["品种码"]: e for e in back["events"]}
    print(f"\n备份：{bak}")
    print(f"回核·条数 {len(back['events'])} {'✔' if len(back['events']) == 10 else '✘'}")
    print(f"回核·scan_date {back['scan_date']} / valid_until {back['valid_until']} "
          f"{'✔' if back['valid_until'] >= UNTIL else '✘ 未覆盖 compare_date'}")
    print(f"回核·催化非空 {sum(1 for e in back['events'] if e['催化'].strip())}/10 · "
          f"卖方预警非空 {sum(1 for e in back['events'] if e['卖方预警'].strip())}/10")
    bad = [v for v in NEW if bmap[v]["催化"] != NEW[v]["催化"]]
    print(f"回核·催化已落盘一致 {'✔' if not bad else '✘ ' + str(bad)}")
    untouched = [v for v in NEW for k in ("品种", "风险类别", "真实风险", "买方窗口")
                 if bmap[v][k] != old_map[v][k]]
    print(f"回核·非白名单字段零改动 {'✔' if not untouched else '✘ ' + str(untouched)}")
    print(f"回核·真实风险分布 {[(e['品种码'], e['真实风险']) for e in back['events']]}")
    print(f"\n▶ 非例行事件扫描刷新完成（10/26 周一 08:5x）。")



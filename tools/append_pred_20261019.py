    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        data = f.read()
    n_lf_before = data.count("\n")
    n_crlf_before = data.count("\r\n")
    assert n_crlf_before == 0, f"原始文件有 CRLF {n_crlf_before} 处，先查"

    import io

    rows = list(csv.DictReader(io.StringIO(data)))
    fieldnames = list(rows[0].keys())

    dup = [r for r in rows if r["date"].replace("-", "/") == BATCH]
    assert not dup, f"批次 {BATCH} 已存在 {len(dup)} 行，拒绝重复追加"

    assert set(COACH) == set(ORDER) == set(CONTRACT), "品种集合不一致"
    for v in ORDER:
        p, t = COACH[v]
        assert p in ("up", "down"), f"{v}: pred 非法 {p}"
        assert t.count("⚠️") >= 1, f"{v}: 缺反方"
        assert "〔源：" in t or "source" in t, f"{v}: 缺来源标注"

    new = []
    for v in ORDER:
        p, t = COACH[v]
        r = {k: "" for k in fieldnames}
        r["date"] = BATCH
        r["variety"] = v
        r["coach_pred"] = p
        r["coach_reason"] = t
        r["compare_date"] = COMPARE
        r["contract_pred"] = CONTRACT[v]
        new.append(r)

    print(f"\n批次 {BATCH} → compare {COMPARE}：待新增 {len(new)} 行（教练列，user 列留空）")
    for r in new:
        print(f'  {r["variety"]:<4} {r["contract_pred"]:<7} reason {len(r["coach_reason"])} 字')

    if dry:
        print("\n--dry-run：未落盘。")
        return 0

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = f"/tmp/iv_direction_pred.csv.{stamp}.bak"
    shutil.copy2(CSV_PATH, bak)

    tmp = CSV_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        w.writeheader()
        w.writerows(rows + new)
    os.replace(tmp, CSV_PATH)

    # 回核
    with open(CSV_PATH, encoding="utf-8-sig") as f:
        data2 = f.read()
    rows2 = list(csv.DictReader(io.StringIO(data2)))
    added = [r for r in rows2 if r["date"].replace("-", "/") == BATCH]
    assert len(rows2) == len(rows) + 10, "行数异常，拒绝"
    assert len(added) == 10, "本批行数异常"
    assert all(r.get("user_pred") == "" for r in added), "user 列被误写"
    assert all(r.get("actual") == "" for r in added), "actual 被误写"
    assert all(r.get("contract_pred") for r in added), "contract_pred 缺失"
    assert all(r.get("compare_date") == COMPARE for r in added), "compare_date 不一"
    assert data2.count("\r\n") == 0, "出现 CRLF"

    print(f"\n回核：行数 {len(rows)} → {len(rows2)}（+{len(rows2)-len(rows)}）")
    print(f"      本批 {len(added)} 行 · 列数 {len(rows2[0])} · user 列仍空 {sum(1 for r in added if not r['user_pred'])}/10")
    print(f"      LF {n_lf_before} → {data2.count(chr(10))} · CRLF {n_crlf_before} → {data2.count(chr(13)+chr(10))}（须为 0）")
    print(f"      备份 {bak}")
    print("\n▶ 教练列已落盘。**正文与 up/down 计数均不在此回显** —— 等你提交 user 列后，两侧同时亮出。")
    return 0


